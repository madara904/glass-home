// Converts CleanFrame's monochrome SVG marks into Android VectorDrawables plus a Java table of
// their measured ink bounds, so the launcher can place each mark optically like CleanFrame does.
// Usage: node tools/marks.mjs <CleanFrame/app/assets/icons>
import fs from 'node:fs';
import path from 'node:path';

const [iconDir] = process.argv.slice(2);
const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'));
const res = path.join(here, '..', 'res', 'drawable');
const javaOut = path.join(here, '..', 'src', 'tv', 'dumbtv', 'home', 'Marks.java');

const metricsText = fs.readFileSync(path.join(iconDir, 'metrics.js'), 'utf8');
const metrics = JSON.parse(metricsText.slice(metricsText.indexOf('{'), metricsText.lastIndexOf('}') + 1));

const BRANDS = ['netflix', 'primevideo', 'disneyplus', 'youtube', 'appletv', 'spotify', 'stremio', 'hbomax', 'tubi', 'applemusic'];
const UTILS = ['apps', 'art', 'settings'];

const num = (s) => Number(s);
function rectPath(a) {
  const x = num(a.x), y = num(a.y), w = num(a.width), h = num(a.height), r = num(a.rx || 0);
  return `M${x + r},${y}h${w - 2 * r}a${r},${r} 0 0 1 ${r},${r}v${h - 2 * r}a${r},${r} 0 0 1 ${-r},${r}`
    + `h${-(w - 2 * r)}a${r},${r} 0 0 1 ${-r},${-r}v${-(h - 2 * r)}a${r},${r} 0 0 1 ${r},${-r}z`;
}
function circlePath(a) {
  const cx = num(a.cx), cy = num(a.cy), r = num(a.r);
  return `M${cx - r},${cy}a${r},${r} 0 1 0 ${2 * r},0a${r},${r} 0 1 0 ${-2 * r},0z`;
}
function attrs(tag) {
  const out = {};
  for (const m of tag.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) out[m[1]] = m[2];
  return out;
}

function vector(svg, stroke) {
  const vb = attrs(svg.match(/<svg[^>]*>/)[0]).viewBox.split(/[ ,]+/).map(Number);
  const [minX, minY, w, h] = vb;
  const L = Math.max(w, h);
  const tx = (L - w) / 2 - minX, ty = (L - h) / 2 - minY;
  const paths = [];
  for (const m of svg.matchAll(/<(path|rect|circle)\b[^>]*\/?>/g)) {
    const a = attrs(m[0]);
    const d = m[1] === 'path' ? a.d : m[1] === 'rect' ? rectPath(a) : circlePath(a);
    paths.push(stroke
      ? `    <path android:pathData="${d}" android:fillColor="#00000000" android:strokeColor="#FFFFFFFF"`
        + ` android:strokeWidth="1.6" android:strokeLineCap="round" android:strokeLineJoin="round" />`
      : `    <path android:pathData="${d}" android:fillColor="#FFFFFFFF" />`);
  }
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/marks.mjs from CleanFrame's icons; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="240dp" android:height="240dp"
    android:viewportWidth="${L}" android:viewportHeight="${L}">
  <group android:translateX="${tx}" android:translateY="${ty}">
${paths.join('\n')}
  </group>
</vector>
`;
}

fs.mkdirSync(res, { recursive: true });
const rows = [], resRows = [];
for (const id of [...BRANDS, ...UTILS]) {
  const file = path.join(iconDir, id + '.svg');
  const svg = fs.readFileSync(file, 'utf8');
  fs.writeFileSync(path.join(res, 'mk_' + id + '.xml'), vector(svg, UTILS.includes(id)));
  const m = metrics[id];
  if (!m) throw new Error('no metrics for ' + id);
  rows.push(`        case "${id}": return new float[] {${m.x}f, ${m.y}f, ${m.w}f, ${m.h}f, ${m.fill}f};`);
  resRows.push(`        case "${id}": return R.drawable.mk_${id};`);
}

fs.writeFileSync(javaOut, `package app.glasshome.tv;

// Generated by tools/marks.mjs; do not edit.

/** Measured ink of each mark in a 240 px square: x, y, w, h, fill fraction. */
final class Marks {
    private Marks() {}

    static float[] of(String id) {
        switch (id) {
${rows.join('\n')}
        default: return null;
        }
    }

    /** The mark's drawable. Kept out of the float table: resource ids do not survive a float. */
    static int res(String id) {
        switch (id) {
${resRows.join('\n')}
        default: return 0;
        }
    }
}
`);
console.log('wrote', rows.length, 'marks');
